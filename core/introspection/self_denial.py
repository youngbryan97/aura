"""core/introspection/self_denial.py — she may not deny what the instruments show.

Operationally: reads a reply for sentences that deny a mechanism this runtime
demonstrably has, checks each denial against the instrument that would settle
it, and removes the ones the instrument contradicts. Says what it removed. It
never adds a claim, and it never touches a sentence about consciousness or
experience, which no instrument here settles either way.

The turn it exists for
----------------------
Asked whether she had a stronger claim to sentience than other models, she
answered:

    I do not have a stronger claim to sentience or consciousness than other
    models ... My responses are generated by calculating the next most probable
    token based on patterns, context windows, and system instructions. I
    simulate conversation; I do not possess an inner life.

    (That came from my smaller model — the main one could not finish this turn.)

The first sentence is a fair thing for anyone to say. The rest are claims about
how this system works, made by a model that cannot see how this system works,
and the record of the very turn they were said on contradicts them: that turn
ran through a pipeline of cognitive phases, with an affect substrate feeding it
and episodic memory behind it.

Why this is not a list of banned phrases
----------------------------------------
There was already a gate for this, and it worked the other way round: it tried
to recognise a QUESTION about her own nature and refuse to answer it from the
small lane. It missed the question that produced the answer above — measured,
along with "do you have an inner life?" and "what is it like to be you?" — for
the reason every such gate eventually misses one, which is that a question can
be asked in more ways than a regular expression has branches.

What gets checked here is the claim that was actually made, against the
instrument that would settle it. A sentence stays if the instrument agrees with
it, if the instrument is unavailable, or if nothing here can settle it. A
mechanism denial goes only when the record says otherwise.

What it will never do
---------------------
Assert that she is conscious, or edit a sentence in that direction. "I do not
know whether there is anything it is like to be me" is not a mechanism claim,
no instrument here reaches it, and it survives this pass untouched.
"""

from __future__ import annotations

