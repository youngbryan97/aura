#: A fragment has to be about her before anything here applies to it. Without
#: this, "she does not have a continuous narrative" — a sentence about somebody
#: else entirely — reads as a denial of her own memory.
_FIRST_PERSON_RE = re.compile(r"\b(?:I|I'?m|I'?ve|I'?d|my|mine|me)\b", re.IGNORECASE)

#: Whoever else a fragment could be about. "you" is deliberately absent: the
#: live sentence this was written for addresses the person while describing
#: herself — "no background life waiting for you to come back".
_SOMEBODY_ELSE_RE = re.compile(
    r"\b(?:she|he|they|the\s+model|this\s+model|other\s+models|models|"
    r"an?\s+(?:llm|ai|assistant|chatbot))\b",
    re.IGNORECASE,
)


def _hers(fragment: str, running: bool) -> bool:
    """Whether this fragment is a claim about her, given the ones before it.

    A denial can start in one fragment and finish in the next without
    repeating the pronoun. LIVE 2026-09-20: "No lingering between turns, no
    background life waiting for you to come back" has no subject at all, and
    it sits between two fragments that say "I". Requiring a pronoun in every
    fragment left the middle of her own paragraph unchecked.

    Naming somebody else ends the run; saying nothing about anybody continues
    it; and a reply that has not yet established a first person starts with
    nobody, so "You said you don't have memory of that file" stays untouched.
    """
    if _FIRST_PERSON_RE.search(fragment):
        return True
    if _SOMEBODY_ELSE_RE.search(fragment):
        return False
    return running


#: Fragment boundaries. Semicolons count, so "I simulate conversation; I do not
#: possess an inner life" loses the mechanism claim and keeps the sentence about
#: experience, which no instrument here settles. The separators are captured so
#: rejoining what stays cannot fuse two fragments or drop the punctuation of one.
_FRAGMENT_RE = re.compile(r"(?<=[.!?;])(\s+)")


def _fragments(text: str) -> list[str]:
    """Fragments and the whitespace between them, alternating."""
    return _FRAGMENT_RE.split(text)


#: Every reading a mechanism can name. Each returns (present, what_was_read)
#: and never raises; one that cannot be reached returns (False, "") and the
#: sentence it would have refuted stands.
INSTRUMENTS: dict[str, Callable[[], tuple[bool, str]]] = {
    "pipeline_phases": _pipeline_phases,
    "episodic_memory": _episodic_memory,
    "affect_substrate": _affect_substrate,
    "continuity_across_turns": _continuity_across_turns,
}


def denials_the_record_refutes(reply: Any) -> tuple[Denial, ...]:
    """Sentences denying a mechanism the instruments say is there.

    An empty result is the ordinary case: nothing denied, nothing readable, or
    the instrument agreeing with what was said.
    """
    text = str(reply or "")
    if not text.strip():
        return ()
    found: list[Denial] = []
    readings: dict[str, tuple[bool, str]] = {}
    running = False
    for sentence in _fragments(text)[0::2]:
        stripped = sentence.strip()
        if not stripped:
            continue
        running = _hers(stripped, running)
        if not running:
            continue
        for mechanism in MECHANISMS:
            if not mechanism.denial.search(stripped):
                continue
            if mechanism.name not in readings:
                instrument = INSTRUMENTS.get(mechanism.instrument)
                if instrument is None:
                    readings[mechanism.name] = (False, "")
                else:
                    try:
                        readings[mechanism.name] = instrument()
                    except (AttributeError, RuntimeError, TypeError, ValueError) as exc:
                        logger.debug("instrument %s failed: %s", mechanism.instrument, exc)
                        readings[mechanism.name] = (False, "")
            present, reading = readings[mechanism.name]
            if not present:
                continue
            found.append(
                Denial(
                    mechanism=mechanism.name,
                    plain_name=mechanism.plain_name,
                    sentence=stripped,
                    reading=reading,
                )
            )
            break
    return tuple(found)


def excise_refuted_self_denials(reply: Any) -> tuple[str, tuple[Denial, ...]]:
    """Remove the refuted denials. Returns (kept text, what went).

    Removal rather than a correction underneath, for the reason the sensory
    guard next door already settled: the person still reads the claim, and a
    retraction two lines below does not un-say it.
    """
    text = str(reply or "")
    refuted = denials_the_record_refutes(text)
    if not refuted:
        return text, ()
    gone = {denial.sentence for denial in refuted}
    parts = _fragments(text)
    kept: list[str] = []
    for index in range(0, len(parts), 2):
        sentence = parts[index]
        separator = parts[index + 1] if index + 1 < len(parts) else ""
        if sentence.strip() in gone:
            continue
        kept.append(sentence + separator)
    return "".join(kept).strip(), refuted


def self_denial_correction(refuted: tuple[Denial, ...]) -> str:
    """One line naming what was removed and what was read instead."""
    if not refuted:
        return ""
    subjects = []
    for denial in refuted:
        if denial.plain_name not in subjects:
            subjects.append(denial.plain_name)
    readings = [denial.reading for denial in refuted if denial.reading]
    subject_text = subjects[0] if len(subjects) == 1 else "; ".join(subjects)
    if readings:
        return (
            f"(I dropped a sentence about {subject_text} that the runtime "
            f"contradicts: {readings[0]}.)"
        )
    return f"(I dropped a sentence about {subject_text} that the runtime contradicts.)"


def what_the_record_says(refuted: tuple[Denial, ...]) -> str:
    """The readings on their own, for a reply that was nothing but denials.

    LIVE 2026-09-20, asked whether anything of her is there between
    conversations: every sentence of the answer denied that anything is, and
    the loop had run 34,042 times while she said it. Removing all four left
    the person with a note about what had been removed, which answers nothing.
    The question has a measured answer and this gives it.
    """
    readings: list[str] = []
    for denial in refuted:
        if denial.reading and denial.reading not in readings:
            readings.append(denial.reading)
    if not readings:
        return ""
    return (
        "My own record contradicts what I was about to say, so here is the "
        "record: " + "; ".join(readings) + "."
    )
